#!/usr/bin/env bash
# Build the Vulkan rendering ebook website with MDWeb from hand-written markdown.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MDWEB_DIR="${MDWEB_DIR:-$(cd "$REPO_ROOT/../MDWeb" && pwd)}"
OUT_DIR="${OUT_DIR:-$REPO_ROOT/site}"

cd "$MDWEB_DIR"
dotnet build -v q
dotnet run --project src/MDWeb.Cli -- \
  -s "$REPO_ROOT" \
  -o "$OUT_DIR" \
  -t ./themes/default \
  --title "Building a Real-Time Renderer with Vulkan" \
  --description "Learn real-time rendering programming step by step using the Spark engine as a reference implementation" \
  --footer '<p>Generated by <strong>hoihky</strong> with <strong>MDWeb</strong> and with assistance from <strong>AI</strong></p>' 

echo "Site: $OUT_DIR"
echo "Preview: npx serve \"$OUT_DIR\""
